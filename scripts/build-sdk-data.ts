// Generates sdk/src/deployments/data.ts from deployments/mainnet.json. With --check, fails if it is out of date.
// Usage: node scripts/build-sdk-data.ts [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { parse } from "@fleet-sdk/serializer";
import { run } from "../lib/cli.ts";

export const MAINNET_JSON = new URL("../deployments/mainnet.json", import.meta.url);
export const SDK_DATA_TS = new URL("../sdk/src/deployments/data.ts", import.meta.url);

export function renderSdkData(mainnetRecordsPath: URL = MAINNET_JSON): string {
  const content = existsSync(mainnetRecordsPath) ? readFileSync(mainnetRecordsPath, "utf8") : "";
  const data = content ? JSON.parse(content) : { deployments: [] };
  const v3Deployments = [];

  for (const d of data.deployments ?? []) {
    const r9 = d.genesis?.registers?.R9;
    if (typeof r9 !== "string") continue;
    try {
      const decoded = parse(r9);
      if (Array.isArray(decoded) && decoded.length === 2 && typeof decoded[0] === "bigint" && typeof decoded[1] === "bigint") {
        v3Deployments.push({
          name: d.name,
          status: d.status,
          peg: d.peg,
          ergoTree: d.ergoTree,
          address: d.address,
          tokens: {
            nft: { id: d.tokens.nft.id, name: d.tokens.nft.name, decimals: d.tokens.nft.decimals, emission: d.tokens.nft.emission },
            neutron: { id: d.tokens.neutron.id, name: d.tokens.neutron.name, decimals: d.tokens.neutron.decimals, emission: d.tokens.neutron.emission },
            proton: { id: d.tokens.proton.id, name: d.tokens.proton.name, decimals: d.tokens.proton.decimals, emission: d.tokens.proton.emission },
          },
          constants: {
            _MinFee: d.constants._MinFee,
            _OracleFeePk: d.constants._OracleFeePk,
            _OraclePoolNFT: d.constants._OraclePoolNFT,
            _OracleBuybackNFT: d.constants._OracleBuybackNFT,
          },
          genesis: {
            registers: {
              R9: d.genesis.registers.R9,
            },
          },
        });
      }
    } catch {
      // not a valid serialized constant, skip
    }
  }

  v3Deployments.sort((a, b) => a.name.localeCompare(b.name));

  const items = v3Deployments.length === 0 ? "[]" : `[\n${v3Deployments.map((d) => `  ${JSON.stringify(d, null, 2).replace(/\n/g, "\n  ")},`).join("\n")}\n]`;

  return `// Generated by scripts/build-sdk-data.ts from deployments/mainnet.json. Do not edit.\nexport default ${items};\n`;
}

if (process.argv[1] && new URL(`file://${process.argv[1].replace(/\\/g, "/")}`).href === import.meta.url) {
  run(async () => {
    const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } });
    const rendered = renderSdkData();
    if (values.check) {
      const current = existsSync(SDK_DATA_TS) ? readFileSync(SDK_DATA_TS, "utf8").replace(/\r\n/g, "\n") : "";
      if (current !== rendered) throw new Error("sdk/src/deployments/data.ts is out of date: run node scripts/build-sdk-data.ts");
      console.log("sdk/src/deployments/data.ts is up to date");
    } else {
      writeFileSync(SDK_DATA_TS, rendered);
      console.log("wrote sdk/src/deployments/data.ts");
    }
  });
}
